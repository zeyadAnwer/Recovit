#!/usr/bin/env node
/**
 * Lists every headline and sentence on every page (both languages) into
 * docs/redesign/CONTENT-INVENTORY.md and reports duplicates and
 * near-duplicates. Exits with code 1 if any are found.
 *
 *   pnpm build && pnpm content:audit
 */
import { spawn } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';
import { extractUnitsInPage, findDuplicates } from './lib/content-audit.mjs';

const PORT = 4610;
const BASE = `http://localhost:${PORT}`;

const sitemap = readFileSync('dist/client/sitemap-0.xml', 'utf8');
const paths = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => new URL(m[1]).pathname);

const server = spawn(process.execPath, ['dist/server/entry.mjs'], {
  env: { ...process.env, HOST: '127.0.0.1', PORT: String(PORT), EMAIL_PROVIDER: 'test' },
  stdio: 'ignore',
});
await new Promise((resolve) => setTimeout(resolve, 2000));
const browser = await chromium.launch(
  process.env.PW_EXECUTABLE ? { executablePath: process.env.PW_EXECUTABLE } : {},
);
const page = await browser.newPage();
const pages = [];
try {
  for (const path of paths) {
    await page.goto(BASE + path);
    pages.push({
      url: path,
      lang: path.startsWith('/en/') ? 'en' : 'ar',
      units: await page.evaluate(extractUnitsInPage),
    });
  }
} finally {
  await browser.close();
  server.kill();
}

const { exact, near } = findDuplicates(pages);
const esc = (s) => s.replaceAll('|', '\\|');
let md = `# Content inventory\n\nGenerated by \`pnpm content:audit\` from the built site. Scope and method: see [CONTENT-RULES.md](CONTENT-RULES.md#duplicate-check).\n\n`;
md += `**Pages:** ${pages.length} · **Units:** ${pages.reduce((n, p) => n + p.units.length, 0)} · **Exact duplicates:** ${exact.length} · **Near-duplicates (≥ 80 % shared 3-word sequences):** ${near.length}\n\n`;
if (exact.length || near.length) {
  md += `## Duplicates found\n\n| Text | First page | Second page |\n|---|---|---|\n`;
  for (const d of [...exact, ...near]) md += `| ${esc(d.text)} | ${d.first} | ${d.second} |\n`;
  md += '\n';
}
for (const lang of ['ar', 'en']) {
  md += `## ${lang === 'ar' ? 'Arabic' : 'English'}\n\n`;
  for (const p of pages.filter((x) => x.lang === lang)) {
    md += `### \`${p.url}\`\n\n| Kind | Text |\n|---|---|\n`;
    for (const u of p.units) md += `| ${u.kind} | ${esc(u.text)} |\n`;
    md += '\n';
  }
}
writeFileSync('docs/redesign/CONTENT-INVENTORY.md', md);
console.log(`Pages ${pages.length}, exact duplicates ${exact.length}, near-duplicates ${near.length}`);
for (const d of [...exact, ...near]) console.log(`  • "${d.text}"\n      ${d.first}  ↔  ${d.second}`);
process.exit(exact.length || near.length ? 1 : 0);
